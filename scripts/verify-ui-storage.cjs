const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createBackend,createClient,migrationKey}=require('../ui-storage');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE app_kv(key TEXT PRIMARY KEY,value TEXT NOT NULL,updated_at INTEGER NOT NULL)');
const backend=createBackend(()=>db);
const bridge={uiStorageSnapshotSync:()=>backend.snapshot(),uiStorageMigrateSync:items=>backend.migrate(items),uiStorageMutateSync:(k,v,r)=>backend.mutate(k,v,r)};
const values=new Map([['fastgc_script_quick_en','[{"content":"preserved"}]'],['fastgc_script_quick_zh','[]'],['fastgc_global_inbox','stale legacy'],['unrelated_site_data','private'],['fastgc_api_config','obsolete']]);
const legacy={get length(){return values.size},key:i=>[...values.keys()][i],getItem:k=>values.get(k)??null,removeItem:k=>values.delete(k)};
assert.equal(backend.mutate('fastgc_global_inbox','',false).ok,true);
let saved=0;
const first=createClient(bridge,()=>legacy,()=>{},()=>saved++);
assert.equal(first.migratedNow,true);assert.equal(first.getItem('fastgc_script_quick_en'),'[{"content":"preserved"}]');assert.equal(first.getItem('fastgc_script_quick_zh'),'[]');
assert.equal(first.getItem('fastgc_global_inbox'),'','empty SQLite value must not resurrect legacy data');
assert.equal(first.getItem('unrelated_site_data'),null);assert.equal(values.has('fastgc_api_config'),false);assert.equal(values.has('unrelated_site_data'),true);
first.setItem('fastgc_script_quick_en','[]');first.setItem('fastgc_ui_lang','en');first.removeItem('fastgc_global_inbox');
assert.equal(saved,3,'each successful mutation resets the shared failure notification');
assert.equal(first.getItem('fastgc_global_inbox'),null);
let legacyTouched=false;
const second=createClient(bridge,()=>{legacyTouched=true;throw Error('Legacy DOMStorage must not open after migration')});
assert.equal(legacyTouched,false);assert.equal(second.migratedNow,false);assert.equal(second.getItem('fastgc_script_quick_en'),'[]');assert.equal(second.getItem('fastgc_ui_lang'),'en');assert.equal(second.getItem('fastgc_global_inbox'),null);
assert.equal(backend.mutate('arbitrary_key','bad',false).ok,false);
assert.equal(backend.migrate([{key:'fastgc_api_config',value:'secret'}]).ok,false);
let errorShown=false;
const failed={...bridge,uiStorageMutateSync:()=>({ok:false})};
const readOnly=createClient(failed,()=>{throw Error('No legacy access')},()=>{errorShown=true});
assert.throws(()=>readOnly.setItem('fastgc_ui_lang','zh'),/UI_STORAGE_UNAVAILABLE/);assert.equal(errorShown,true);assert.equal(readOnly.getItem('fastgc_ui_lang'),'en');
db.prepare('DELETE FROM app_kv WHERE key=?').run(migrationKey);
const insert=db.prepare('SELECT COUNT(*) AS n FROM app_kv');const before=insert.get().n;
assert.throws(()=>createClient(bridge,()=>({get length(){throw Error('Unreadable old data')}})),/Unreadable old data/);
assert.equal(backend.snapshot().migrated,false);assert.equal(insert.get().n,before);
const originalPrepare=db.prepare.bind(db);
const fake={exec:sql=>db.exec(sql),prepare(sql){if(sql.includes('ON CONFLICT(key) DO NOTHING'))throw Error('Disk failed');return originalPrepare(sql)}};
const broken=createBackend(()=>fake);
assert.equal(broken.migrate([{key:'fastgc_ui_font_size',value:'lg'}]).ok,false);assert.equal(backend.snapshot().migrated,false);assert.equal(insert.get().n,before);
db.close();
console.log(JSON.stringify({passed:true,legacyDataPreserved:true,emptyValuesPreserved:true,subsequentStartupAvoidsDOMStorage:true,writeFailureDoesNotChangeMemory:true,failedMigrationDoesNotMarkComplete:true,unknownKeysRejected:true}));
